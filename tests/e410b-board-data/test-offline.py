"""Offline package and exact qualified ath10k parser controls; no AP access."""
import argparse
import hashlib
import importlib.util
import json
import lzma
import os
import re
from pathlib import Path
import subprocess
import tarfile
import tempfile
import io

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--base', type=Path, required=True)
p.add_argument('--oem-content', type=Path, required=True)
p.add_argument('--core', type=Path, required=True)
args = p.parse_args()
repo = Path(__file__).resolve().parents[2]
script = repo/'ath10k-ct-firmware/files/cambium-e410b-board-data.py'
spec = importlib.util.spec_from_file_location('packer', script)
packer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(packer)
checks = []
def check(name, condition):
    assert condition, name
    checks.append(name)
def refuses(name, action):
    try:
        action()
    except (ValueError, OSError):
        checks.append(name)
    else:
        raise AssertionError(name)
sha = lambda x: hashlib.sha256(x).hexdigest()
base = args.base.read_bytes()
content = args.oem_content.read_bytes()
check('reviewed OEM container hash', sha(content) == '9d07c48c8443949a4c6ea7ec5ca45452949c25c779cb285e30b63de2e06694c8')
decoder = lzma.LZMADecompressor()
with tarfile.open(fileobj=io.BytesIO(decoder.decompress(content[content.index(b'\xfd7zXZ\0'):])), mode='r:') as archive:
    asset = archive.extractfile('./lib/firmware/IPQ4019/hw.1/boardData_1_0_IPQ4019_Y9803_wifi1.bin').read()
result = packer.prepare(base, asset, 'E410B', '5g', 17)
old, new = packer.entries(base), packer.entries(result)
check('original complete archive prefix identical', result[:len(base)] == base)
check('exactly one extra variant', len(new) == len(old)+1 and new[packer.NAME] == asset)
check('all50 original entries unchanged', len(old) == 50 and all(new[n] == v for n,v in old.items()))
for label, model, radio, bid in [('wrong model','E410','5g',17), ('wrong radio','E410B','2g',17), ('wrong ID','E410B','5g',16)]:
    refuses(label, lambda model=model,radio=radio,bid=bid: packer.prepare(base,asset,model,radio,bid))
refuses('wrong base', lambda: packer.prepare(base+b'\0',asset,'E410B','5g',17))
refuses('missing bytes', lambda: packer.prepare(base,b'','E410B','5g',17))
refuses('truncated asset', lambda: packer.prepare(base,asset[:-1],'E410B','5g',17))
bad=bytearray(asset);bad[10]^=1
refuses('bad checksum', lambda: packer.prepare(base,bytes(bad),'E410B','5g',17))
bad[12]^=1
words=packer.struct.unpack('<'+'H'*(len(bad)//2),bad);xor=0
for word in words:xor^=word
check('wrong-hash negative has genuinely valid checksum',xor==0xffff)
refuses('wrong hash with valid XOR', lambda: packer.prepare(base,bytes(bad),'E410B','5g',17))
refuses('duplicate ambiguous variant', lambda: packer.entries(result+result[len(base):]))
refuses('malformed TLV', lambda: packer.entries(result[:-1]))

with tempfile.TemporaryDirectory(prefix='e410b-bdf-offline-') as directory:
    tmp=Path(directory);private=tmp/'private.bin';private.write_bytes(asset);private.chmod(0o600)
    original=tmp/'original.bin';original.write_bytes(base)
    generated=tmp/'generated.bin'
    cmd=['python3',str(script),'--base',str(original),'--asset',str(private),'--output',str(generated),'--model','E410B','--radio','5g','--board-id','17']
    subprocess.run(cmd,check=True)
    check('CLI exact generated bytes',generated.read_bytes()==result)
    check('packaged BDF mode0644',generated.stat().st_mode&0o777==0o644)
    def reject_cli(name, replacements):
        generated.write_bytes(b'original sentinel')
        call=cmd.copy()
        for key,value in replacements.items():call[call.index(key)+1]=str(value)
        run=subprocess.run(call,capture_output=True,text=True)
        check(name,run.returncode!=0 and generated.read_bytes()==b'original sentinel')
    reject_cli('missing private path refuses without output mutation',{'--asset':tmp/'absent'})
    reject_cli('empty private path refuses without output mutation',{'--asset':''})
    reject_cli('wrong radio CLI refuses without output mutation',{'--radio':'2g'})
    reject_cli('wrong model CLI refuses without output mutation',{'--model':'E410'})
    reject_cli('missing output directory refuses without old output mutation',{'--output':tmp/'absent-directory/board-2.bin'})
    sentinel=tmp/'sentinel';sentinel.write_bytes(b'symlink sentinel')
    generated.unlink();generated.symlink_to(sentinel)
    check('symlink refuses without target mutation',subprocess.run(cmd,capture_output=True).returncode!=0 and sentinel.read_bytes()==b'symlink sentinel')
    generated.unlink();generated.write_bytes(result)

    # Compile the unmodified functions used by the qualified driver. Only
    # logging/firmware acquisition and containing kernel structures are stubbed.
    core=args.core.read_text()
    parser_source=core[core.index('static int ath10k_core_parse_bd_ie_board('):core.index('static int ath10k_core_create_board_name(')]
    shim=r'''
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <string.h>
#include <stdio.h>
#include <errno.h>
typedef uint8_t u8;
#define ALIGN(n,a) (((n)+(a)-1)&~((a)-1))
#define le32_to_cpu(n) (n)
#define ATH10K_BD_IE_BOARD 0
#define ATH10K_BD_IE_BOARD_EXT 1
#define ATH10K_BD_IE_BOARD_NAME 0
#define ATH10K_BD_IE_BOARD_DATA 1
#define ATH10K_BOARD_MAGIC "QCA-ATH10K-BOARD"
#define ATH10K_DBG_BOOT 0
#define ath10k_err(...) ((void)0)
#define ath10k_warn(...) ((void)0)
#define ath10k_dbg(...) ((void)0)
#define ath10k_dbg_dump(...) ((void)0)
#define IS_ERR(p) (false)
#define PTR_ERR(p) (-EINVAL)
#define strlcpy(d,s,n) snprintf(d,n,"%s",s)
struct ath10k_fw_ie { uint32_t id,len; u8 data[]; };
struct firmware { const u8*data; size_t size; };
struct ath10k {struct { const struct firmware*board; const u8*board_data,*ext_board_data; size_t board_len,ext_board_len; struct {char fw_board_name[128];}fw_file;}normal_mode_fw; struct {struct {const char*dir;}fw;}hw_params;};
static const struct firmware*ath10k_fetch_fw_file(struct ath10k*a,const char*d,const char*f){abort();}
static void ath10k_core_free_board_files(struct ath10k*a){}
'''
    main=r'''
int main(int argc,char**argv){
 if(argc!=4)return 2;FILE*f=fopen(argv[1],"rb");if(!f)return 3;
 fseek(f,0,SEEK_END);long n=ftell(f);rewind(f);u8*b=malloc(n);if(fread(b,1,n,f)!=(size_t)n)return 4;fclose(f);
 struct firmware fw={b,n};struct ath10k a={0};a.normal_mode_fw.board=&fw;a.hw_params.fw.dir="fixture";
 int ret=ath10k_core_fetch_board_data_api_n(&a,argv[2],argv[3][0]?argv[3]:NULL,"board-2.bin");
 if(ret)return 1;fwrite(a.normal_mode_fw.board_data,1,a.normal_mode_fw.board_len,stdout);return 0;
}
'''
    c=tmp/'parser.c';c.write_text(shim+parser_source+main)
    exe=tmp/'parser';subprocess.run(['cc','-std=gnu11','-o',str(exe),str(c)],check=True,capture_output=True)
    def selected(archive,name,fallback):
        run=subprocess.run([str(exe),str(archive),name,fallback],capture_output=True)
        return run.returncode,run.stdout
    generic17='bus=ahb,bmi-chip-id=0,bmi-board-id=17'
    check('original negative: variant absent falls back old generic17',selected(original,packer.NAME,generic17)==(0,old[generic17]))
    check('actual driver variant-first picks OEM17 despite earlier generic17',selected(generated,packer.NAME,generic17)==(0,asset))
    for bid in (16,17,20,21):
        name=f'bus=ahb,bmi-chip-id=0,bmi-board-id={bid}'
        check(f'actual driver generic{bid} unchanged',selected(generated,name,name)==(0,old[name]))
    wrong='bus=ahb,bmi-chip-id=0,bmi-board-id=16,variant='+packer.VARIANT
    check('wrong-radio variant absent',selected(generated,wrong,'')[0]!=0)
    check('actual driver missing candidate without fallback refuses',selected(original,packer.NAME,'')[0]!=0)
    check('wrong chip variant refuses',selected(generated,packer.NAME.replace('chip-id=0','chip-id=1'),'')[0]!=0)

    loader=repo/'ipq40xx/base-files/etc/hotplug.d/firmware/11-ath10k-caldata'
    oldloader=subprocess.check_output(['git','show','d406aede:'+str(loader.relative_to(repo))],cwd=repo)
    check('factory calibration loader source byte unchanged',loader.read_bytes()==oldloader)
    body=loader.read_text().replace('. /lib/functions/caldata.sh','# test-only calibrated extraction boundary stubs')
    check('test-only loader boundary replacement unique',loader.read_text().count('. /lib/functions/caldata.sh')==1)
    cal=tmp/'hotplug.sh'
    for model in ('cambiumnetworks,e410','cambium,e410','cambiumnetworks,e410b'):
        for address,offset in (('a000000','0x1000'),('a800000','0x5000')):
            stub='board_name(){ echo '+model+'; }\ncaldata_extract(){ printf "extract:%s:%s:%s\\n" "$1" "$2" "$3"; }\nmtd_get_mac_binary(){ echo 00:11:22:33:44:55; }\nath10k_patch_mac(){ printf "mac:%s\\n" "$1"; }\n'
            cal.write_text(stub+body)
            run=subprocess.run(['bash',str(cal)],env=dict(os.environ,FIRMWARE='ath10k/pre-cal-ahb-'+address+'.wifi.bin'),capture_output=True,text=True)
            check('actual hotplug '+model+' '+address,run.returncode==0 and run.stdout=='extract:0:ART:'+offset+':0x2f20\nmac:00:11:22:33:44:55\n')

    makefile=repo/'ath10k-ct-firmware/Makefile'
    prior=subprocess.check_output(['git','show','d406aede:ath10k-ct-firmware/Makefile'],cwd=repo,text=True)
    pattern=r'^define (Package/[^\n]+/install)\n(.*?)^endef'
    original_recipes=dict(re.findall(pattern,prior,re.M|re.S))
    current_recipes=dict(re.findall(pattern,makefile.read_text(),re.M|re.S))
    check('all non-target install recipes byte unchanged',set(original_recipes)==set(current_recipes) and all(current_recipes[n]==v for n,v in original_recipes.items()if n!='Package/ath10k-firmware-qca4019-ct-htt/install'))

    # Exercise the actual package install recipe, with only OpenWrt's build
    # framework/macros stubbed. The executable firmware is an unchanged fixture.
    framework=tmp/'framework';framework.mkdir();(framework/'rules.mk').write_text('INCLUDE_DIR:='+str(framework)+'\n')
    (framework/'package.mk').write_text('')
    host=tmp/'host/bin';host.mkdir(parents=True);(host/'python3').symlink_to(subprocess.check_output(['which','python3'],text=True).strip())
    downloads=tmp/'dl';downloads.mkdir()
    (downloads/'ath10k-firmware-d622d160e9f552ead68d9ae81b715422892dc2ef-qca4019-board-2.bin').write_bytes(base)
    fwname='QCA4019-firmware-5-ct-htt-mgt-community-12.bin-lede.021'
    (downloads/fwname).write_bytes(b'unchanged executable firmware fixture')
    harness=tmp/'package.mk'
    harness.write_text('TOPDIR:='+str(framework)+'\nSTAGING_DIR_HOST:='+str(tmp/'host')+'\nDL_DIR:='+str(downloads)+'\nINSTALL_DIR:=mkdir -p\nINSTALL_DATA:=install -m0644\ninclude '+str(repo/'ath10k-ct-firmware/Makefile')+'\nall:\n\t$(call Package/ath10k-firmware-qca4019-ct-htt/install,$(DEST))\n')
    def package(dest,config,assetpath):
        return subprocess.run(['make','-f',str(harness),'all','DEST='+str(dest),config+'=y','CAMBIUM_E410B_5G_BDF='+str(assetpath)],cwd=repo/'ath10k-ct-firmware',capture_output=True,text=True)
    for config in ('CONFIG_TARGET_ipq40xx_generic_DEVICE_cambium-sage','CONFIG_TARGET_DEVICE_ipq40xx_generic_DEVICE_cambium-sage'):
        dest=tmp/config;run=package(dest,config,private)
        check('actual install '+config,run.returncode==0)
        check('actual packaged variant bytes '+config,(dest/'lib/firmware/ath10k/QCA4019/hw1.0/board-2.bin').read_bytes()==result)
        check('actual packaged firmware unchanged '+config,(dest/'lib/firmware/ath10k/QCA4019/hw1.0/ct-firmware-5.bin').read_bytes()==b'unchanged executable firmware fixture')
    check('actual Sage package missing asset fails',package(tmp/'missing','CONFIG_TARGET_ipq40xx_generic_DEVICE_cambium-sage',tmp/'absent').returncode!=0)
    dest=tmp/'other';run=package(dest,'CONFIG_TARGET_ipq40xx_generic_DEVICE_other',tmp/'absent')
    check('other target needs no private asset and archive unchanged',run.returncode==0 and (dest/'lib/firmware/ath10k/QCA4019/hw1.0/board-2.bin').read_bytes()==base)
print(json.dumps(dict(status='PASS',controls=len(checks),checks=checks,base_sha256=sha(base),private_asset_sha256=sha(asset),result_sha256=sha(result),result_bytes=len(result),actual_driver_parser_source_sha256=sha(parser_source.encode()),scope='Offline package/stock-parser tests only; no AP/RF/power-loss acceptance'),indent=2))
